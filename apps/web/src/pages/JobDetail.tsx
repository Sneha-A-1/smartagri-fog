import { CartesianGrid, Legend, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Link, useParams } from "react-router-dom";
import { useCancelJob, useJob, useJobResult, usePlugins } from "@/api/hooks";
import { Button } from "@/components/Button";
import { ProgressBar } from "@/components/ProgressBar";
import {
  type ComparisonResult,
  ComparisonView,
  type SingleRunResult,
  SingleRunView,
} from "@/components/SimulationResults";
import {
  type DagComparisonResult,
  DagComparisonView,
  type DagScheduleResult,
  DagScheduleView,
  type EEGResult,
  EEGCaseStudyView,
  type StrategyComparisonResult,
  StrategyComparisonView,
} from "@/components/CaseStudyResults";
import {
  type DQNTrainingResult,
  DQNTrainingView,
  type OptimizerBenchmarkResult,
  OptimizerBenchmarkView,
} from "@/components/OptimizationResults";
import { OriginBadge } from "@/components/StatusBadge";
import { formatDuration, formatTime } from "@/lib/format";

type SoilResult = {
  data_origin: string;
  hours: number[];
  true_moisture: number[];
  measured_moisture: number[];
  rain_events: { day: number; rain_mm: number }[];
  summary: Record<string, number>;
};

const SUMMARY_LABELS: Record<string, string> = {
  n_readings: "Readings",
  mean: "Mean (m³/m³)",
  min: "Lowest (m³/m³)",
  max: "Highest (m³/m³)",
  rain_days: "Rain days",
};

export default function JobDetail() {
  const { jobId = "" } = useParams();
  const { data: job, isLoading } = useJob(jobId);
  const { data: plugins } = usePlugins();
  const { data: result } = useJobResult(jobId, job?.status === "succeeded" && job.has_result);
  const cancel = useCancelJob();

  if (isLoading) return <p className="text-sm text-ink-3">Loading…</p>;
  if (!job) return <p className="text-sm text-danger">Job not found.</p>;

  const plugin = plugins?.find((p) => p.id === job.plugin_id);
  const active = job.status === "running" || job.status === "queued";
  const soil = job.plugin_id === "data_generator:soil_moisture_demo" ? (result as SoilResult | undefined) : undefined;
  const kind = (result as { kind?: string } | undefined)?.kind;

  return (
    <article>
      <Link to="/jobs" className="text-sm text-ink-3 hover:text-accent">
        Jobs
      </Link>
      <header className="mt-2 mb-6 flex flex-wrap items-start justify-between gap-4">
        <div>
          <h1 className="text-[1.65rem] font-semibold tracking-[-0.01em]">{plugin?.name ?? job.plugin_id}</h1>
          <p className="mt-1 text-sm text-ink-2">
            <span className="capitalize">{job.status}</span>. Started {formatTime(job.started_at ?? job.created_at)},
            took {formatDuration(job.started_at, job.finished_at)}.
          </p>
        </div>
        {active && (
          <Button onClick={() => cancel.mutate(job.id)} disabled={cancel.isPending}>
            Cancel job
          </Button>
        )}
      </header>

      <div className="max-w-xl">
        <ProgressBar value={job.progress} status={job.status} />
        <p className="mt-2 text-sm text-ink-2">{job.message}</p>
        {job.error && <p className="mt-2 text-sm text-danger">{job.error}</p>}
      </div>

      {soil && (
        <section className="mt-10">
          <div className="flex flex-wrap items-baseline justify-between gap-3">
            <h2 className="text-lg font-semibold">Soil moisture over time</h2>
            <OriginBadge origin={soil.data_origin} />
          </div>
          <p className="mt-1 max-w-2xl text-sm text-ink-2">
            Generated by an uncalibrated demo model: the soil dries toward the wilting point and rain events refill it.
            {` ${soil.rain_events.length} rain event${soil.rain_events.length === 1 ? "" : "s"} in ${job.params.days} days.`}
          </p>
          <div className="mt-4 h-80 w-full">
            <ResponsiveContainer>
              <LineChart
                data={soil.hours.map((h, i) => ({ day: h / 24, true: soil.true_moisture[i], measured: soil.measured_moisture[i] }))}
                margin={{ top: 8, right: 16, bottom: 8, left: 0 }}
              >
                <CartesianGrid stroke="var(--line)" vertical={false} />
                <XAxis
                  dataKey="day"
                  type="number"
                  domain={[0, "dataMax"]}
                  tickFormatter={(d: number) => d.toFixed(0)}
                  stroke="var(--ink-3)"
                  fontSize={12}
                  label={{ value: "Day", position: "insideBottomRight", offset: -4, fill: "var(--ink-3)", fontSize: 12 }}
                />
                <YAxis
                  stroke="var(--ink-3)"
                  fontSize={12}
                  domain={["auto", "auto"]}
                  tickFormatter={(v: number) => v.toFixed(2)}
                  label={{ value: "m³/m³", angle: -90, position: "insideLeft", fill: "var(--ink-3)", fontSize: 12 }}
                />
                <Tooltip
                  contentStyle={{ background: "var(--surface)", border: "1px solid var(--line)", borderRadius: 8 }}
                  formatter={(v) => (typeof v === "number" ? v.toFixed(3) : String(v))}
                  labelFormatter={(d) => `Day ${Number(d).toFixed(2)}`}
                />
                <Legend wrapperStyle={{ fontSize: 13 }} />
                <Line name="Measured (with sensor noise)" dataKey="measured" stroke="var(--ink-3)" dot={false} strokeWidth={1} isAnimationActive={false} />
                <Line name="True soil moisture" dataKey="true" stroke="var(--accent)" dot={false} strokeWidth={2} isAnimationActive={false} />
              </LineChart>
            </ResponsiveContainer>
          </div>
          <dl className="mt-6 grid grid-cols-2 gap-4 text-sm sm:grid-cols-5">
            {Object.entries(soil.summary).map(([k, v]) => (
              <div key={k}>
                <dt className="text-ink-3">{SUMMARY_LABELS[k] ?? k.replace(/_/g, " ")}</dt>
                <dd className="text-lg tabular-nums">{v}</dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {kind === "simulation.single_run" && <SingleRunView result={result as SingleRunResult} />}
      {kind === "simulation.comparison" && <ComparisonView result={result as ComparisonResult} />}
      {kind === "simulation.case_study.ifogsim_eeg" && <EEGCaseStudyView result={result as EEGResult} />}
      {kind === "scheduler.dag_schedule" && <DagScheduleView result={result as DagScheduleResult} />}
      {kind === "simulation.dag_comparison" && <DagComparisonView result={result as DagComparisonResult} />}
      {kind === "simulation.strategy_comparison" && <StrategyComparisonView result={result as StrategyComparisonResult} />}
      {kind === "simulation.optimizer_benchmark" && <OptimizerBenchmarkView result={result as OptimizerBenchmarkResult} />}
      {kind === "simulation.dqn_training" && <DQNTrainingView result={result as DQNTrainingResult} />}

      <ParamsSection params={job.params} />
    </article>
  );
}

function ParamsSection({ params }: { params: Record<string, unknown> }) {
  const text = JSON.stringify(params, null, 2);
  const large = text.length > 2500;
  const pre = (
    <pre className="mt-3 max-h-[32rem] overflow-auto rounded-lg border border-line bg-surface p-4 text-xs leading-relaxed">{text}</pre>
  );
  return (
    <section className="mt-10">
      <h2 className="text-lg font-semibold">Parameters used</h2>
      {large ? (
        <details className="mt-2 text-sm">
          <summary className="cursor-pointer text-ink-2">Show all parameters ({Math.round(text.length / 1024)} KB, includes the full network and workload)</summary>
          {pre}
        </details>
      ) : (
        pre
      )}
    </section>
  );
}
